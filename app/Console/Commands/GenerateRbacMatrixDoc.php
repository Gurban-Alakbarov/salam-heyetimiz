<?php

namespace App\Console\Commands;

use App\Domain\Admin\Authorization\Permission;
use App\Domain\Admin\Authorization\RolePermissionMatrix;
use App\Domain\Admin\Enums\AdminRole;
use Illuminate\Console\Command;

/**
 * docs:rbac — regenerate docs/RBAC_PERMISSION_MATRIX.md from the code (admin audit phase 3: the hand-written matrix
 * had drifted to 44 permissions while the code had 57). Source of truth stays Permission + RolePermissionMatrix;
 * these are the DEFAULT role templates — panel edits live in the DB (role_permissions) and survive deploys.
 */
final class GenerateRbacMatrixDoc extends Command
{
    protected $signature = 'docs:rbac {--path=docs/RBAC_PERMISSION_MATRIX.md}';

    protected $description = 'Regenerate the RBAC permission matrix document from the code';

    public function handle(): int
    {
        $roles = array_values(array_filter(AdminRole::cases(), fn (AdminRole $r): bool => ! $r->isSuperAdmin()));
        $matrix = RolePermissionMatrix::map();
        $notInUse = Permission::notInUse();
        $scopable = Permission::complexScopable();
        $defs = Permission::definitions();

        $lines = [
            '# RBAC — Permission Matrix',
            '',
            '> Generated by `php artisan docs:rbac` on '.now()->toDateString().' — do not edit by hand.',
            '> Source of truth: `App\\Domain\\Admin\\Authorization\\Permission` (catalog) + `RolePermissionMatrix` (DEFAULT role',
            '> templates). Panel edits to role templates and per-admin grants live in the DB and survive deploys',
            '> (`role_permission_seeds`).',
            '',
            '**'.count($defs).' permissions.** Super Admin (**S**) implicitly holds every one. ✓ = granted by default.',
            '_unused_ = no endpoint checks it yet. ⊘ = can never be held by a Kompleks Meneceri (served by endpoints that',
            'are not complex-scoped, so it would show other complexes).',
            '',
            '| Group | Permission | Label | S | '.implode(' | ', array_map(fn (AdminRole $r): string => $r->label(), $roles)).' |',
            '|---|---|---|:--:|'.str_repeat(':--:|', count($roles)),
        ];
        foreach ($defs as $key => $def) {
            $cells = array_map(function (AdminRole $r) use ($matrix, $key, $scopable): string {
                if ($r === AdminRole::ComplexManager && ! in_array($key, $scopable, true)) {
                    return '⊘';
                }

                return in_array($key, $matrix[$r->value] ?? [], true) ? '✓' : '';
            }, $roles);
            $label = $def['label'].(in_array($key, $notInUse, true) ? ' _unused_' : '');
            $lines[] = "| {$def['group']} | `{$key}` | {$label} | ✓ | ".implode(' | ', $cells).' |';
        }

        $lines[] = '';
        $lines[] = '## Defaults per role';
        foreach ($roles as $r) {
            $keys = $matrix[$r->value] ?? [];
            $lines[] = '';
            $lines[] = '### '.$r->label().' (`'.$r->value.'`) — '.count($keys).' permissions'.($r->isComplexScoped() ? ' · own complex only' : '');
            $lines[] = implode(', ', array_map(fn (string $k): string => '`'.$k.'`', $keys));
        }
        $lines[] = '';

        $path = base_path((string) $this->option('path'));
        file_put_contents($path, implode("\n", $lines));
        $this->info('Written '.$path.' ('.count($defs).' permissions, '.count($roles).' roles + super).');

        return self::SUCCESS;
    }
}
